#
# 「each」メソッドを使用することで、「array」配列の要素を１つずつ
# 取り出して処理を行うことができます。
# 「array = [1, 2, 3]」の配列について考えてみます。
#
#   copy_array = []
#   array.each do |element|
#     コピー処理
#   end
#
#   1週目：「element」には「1」が代入される
#          「copy_array」に追加
#
#   2週目：「element」には「2」が代入される
#          「copy_array」に追加
#
#   3週目：「element」には「3」が代入される
#          「copy_array」に追加
#
# これで「copy_array」が「array」のコピーになりそうです。
#
# Rubyには配列に要素を追加する「push」メソッドがあります。
#
#   temp = []
