# 配列をコピーした配列を返すメソッドを定義してください。
# 引数「array」は配列です。

### 例 ###
# array_copy([1, 2, 3]) => [1, 2, 3]
# array_copy(['a', 'b', 'c', 'd', 'e']) => ['a', 'b', 'c', 'd', 'e']

### 条件 ###
# ・Arrayクラスのコピー用のメソッド(「dup」「clone」など)は使用しないでください。

### 配列をコピーする意味 ###
# あるメソッドに引数「array」を渡したとします。
# このとき、メソッド内で「array」の要素をいじると
# 引数「array」の要素も変わります。
# 下記のメソッドがあるとします。
#
#   def temp_method(array)
#     array[0] = 'a'
#   end
#
# このメソッドを実行すると、結果は下記のようになります。
#
#   array = [1, 2, 3]
#   puts "before: #{array}" #=> 「before: [1, 2, 3]」と表示される
#   temp_method(array)
#   puts "after: #{array}"  #=> 「after: ["a", 2, 3]」と表示される
#
# 配列「array」の１つ目の要素が変更されていることが分かると思います。
# メソッドに配列を渡したとき、渡した配列の要素が変更されるメソッドを
# 「破壊的なメソッド」と呼びます。
#
# ちなみに、引数が整数だった場合は下記のようになります。
#
#   def temp_method2(number)
#     number = 999
#   end
#
# number = 1
# puts "before: #{number}" #=> 「before: 1」と表示される
# temp_method2(number)
# puts "after: #{number}"  #=> 「after: 1」と表示される
#
# 変数「number」の値が変わっていないことが分かります。
#
# 上記の理由から、配列(おそらく'ハッシュ'も)のメソッドを使用するときは、
# 「破壊的」か「非破壊的」か意識する必要があります。
#
# Ruby以外の多くの言語でも同様の性質があるため、注意してください。
# (「参照型 変数」とかで調べてもらうと詳しく分かるかもしれません)
#
# 「元々の配列に影響を与えたくないが、配列の値を利用したい」ときなど、
# 配列をコピーして、コピーした方の配列を使うことがあります。

